    TFORM_PAIR(GHOSTCODE_PAIR_SHADOW, COLOR_BLACK, COLOR_BLACK, 16, 16);
    TFORM_PAIR(GHOSTCODE_PAIR_ANNOTATION_BOX_1, COLOR_BLACK, COLOR_GREEN, 16, 46);
    TFORM_PAIR(GHOSTCODE_PAIR_ANNOTATION_BOX_2, COLOR_BLACK, COLOR_CYAN, 16, 51);
    TFORM_PAIR(GHOSTCODE_PAIR_ANNOTATION_BOX_3, COLOR_BLACK, COLOR_MAGENTA, 16, 201);
