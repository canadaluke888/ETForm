static inline short ghostcode_image_color_pair(uint16_t color) {
    if (!has_colors() || COLORS < 256 ||
        COLOR_PAIRS < GHOSTCODE_IMAGE_PAIR_BASE + GHOSTCODE_IMAGE_COLOR_COUNT ||
        color < GHOSTCODE_IMAGE_COLOR_FIRST ||
        color >= GHOSTCODE_IMAGE_COLOR_FIRST + GHOSTCODE_IMAGE_COLOR_COUNT) {
        return 0;
    }
    return (short)(GHOSTCODE_IMAGE_PAIR_BASE + color - GHOSTCODE_IMAGE_COLOR_FIRST);
}

static inline int ghostcode_color_pair(short pair) {
    return has_colors() ? COLOR_PAIR(pair) : A_REVERSE;
}

static inline void ghostcode_set_normal_theme(void) {
    if (has_colors()) {
        attrset(COLOR_PAIR(GHOSTCODE_PAIR_NORMAL));
        bkgd(COLOR_PAIR(GHOSTCODE_PAIR_NORMAL));
    } else {
        attrset(A_NORMAL);
    }
}

