static inline void ghostcode_init_editor_theme(void) {
    if (!has_colors()) {
        return;
    }

    start_color();
    init_pair(GHOSTCODE_PAIR_NORMAL, COLOR_WHITE, COLOR_BLACK);
    init_pair(GHOSTCODE_PAIR_HEADER, COLOR_BLACK, COLOR_CYAN);
    init_pair(GHOSTCODE_PAIR_FOOTER, COLOR_BLACK, COLOR_WHITE);
    init_pair(GHOSTCODE_PAIR_SELECTION, COLOR_BLACK, COLOR_YELLOW);
    init_pair(GHOSTCODE_PAIR_APPLIED, COLOR_BLACK, COLOR_GREEN);
    init_pair(GHOSTCODE_PAIR_CURSOR, COLOR_BLACK, COLOR_MAGENTA);
    init_pair(GHOSTCODE_PAIR_DIALOG, COLOR_WHITE, COLOR_BLUE);
    init_pair(GHOSTCODE_PAIR_FOOTER_TEXT, COLOR_WHITE, COLOR_BLACK);
    init_pair(GHOSTCODE_PAIR_FOOTER_KEY, COLOR_CYAN, COLOR_BLACK);
    init_pair(GHOSTCODE_PAIR_FOOTER_SEPARATOR, COLOR_BLUE, COLOR_BLACK);
    init_pair(GHOSTCODE_PAIR_FOOTER_BORDER, COLOR_WHITE, COLOR_BLACK);
    init_pair(GHOSTCODE_PAIR_SHADOW, COLOR_BLACK, COLOR_BLACK);
    init_pair(GHOSTCODE_PAIR_ANNOTATION_BOX_1, COLOR_BLACK, COLOR_GREEN);
    init_pair(GHOSTCODE_PAIR_ANNOTATION_BOX_2, COLOR_BLACK, COLOR_CYAN);
    init_pair(GHOSTCODE_PAIR_ANNOTATION_BOX_3, COLOR_BLACK, COLOR_MAGENTA);
    init_pair(GHOSTCODE_PAIR_PICKER_DIR, COLOR_CYAN, COLOR_BLACK);
    init_pair(GHOSTCODE_PAIR_PICKER_FILE, COLOR_WHITE, COLOR_BLACK);
    init_pair(GHOSTCODE_PAIR_PICKER_ANNOTATED, COLOR_YELLOW, COLOR_BLACK);
    init_pair(GHOSTCODE_PAIR_FORM_BORDER_SELECTED, COLOR_YELLOW, COLOR_BLACK);
    init_pair(GHOSTCODE_PAIR_SYNTAX_COMMENT, COLOR_BLUE, COLOR_BLACK);
    init_pair(GHOSTCODE_PAIR_SYNTAX_STRING, COLOR_GREEN, COLOR_BLACK);
    init_pair(GHOSTCODE_PAIR_SYNTAX_NUMBER, COLOR_MAGENTA, COLOR_BLACK);
    init_pair(GHOSTCODE_PAIR_SYNTAX_KEYWORD, COLOR_CYAN, COLOR_BLACK);
    init_pair(GHOSTCODE_PAIR_SYNTAX_TYPE, COLOR_YELLOW, COLOR_BLACK);
    init_pair(GHOSTCODE_PAIR_SYNTAX_PREPROCESSOR, COLOR_MAGENTA, COLOR_BLACK);
    init_pair(GHOSTCODE_PAIR_SYNTAX_OPERATOR, COLOR_WHITE, COLOR_BLACK);
    init_pair(GHOSTCODE_PAIR_ANNOTATION_BOX_4, COLOR_BLACK, COLOR_YELLOW);
    init_pair(GHOSTCODE_PAIR_ANNOTATION_BOX_5, COLOR_WHITE, COLOR_BLUE);
    init_pair(GHOSTCODE_PAIR_ANNOTATION_BOX_6, COLOR_WHITE, COLOR_RED);
    init_pair(GHOSTCODE_PAIR_ANNOTATION_BOX_7, COLOR_BLACK, COLOR_WHITE);
    init_pair(GHOSTCODE_PAIR_GUTTER_MARKER, COLOR_RED, COLOR_BLACK);
    init_pair(GHOSTCODE_PAIR_CURSOR_ALT, COLOR_WHITE, COLOR_RED);
    init_pair(GHOSTCODE_PAIR_ANNOTATION_TITLE, COLOR_YELLOW, COLOR_BLACK);
    init_pair(GHOSTCODE_PAIR_ANNOTATION_RANGE, COLOR_CYAN, COLOR_BLACK);
    bkgd(COLOR_PAIR(GHOSTCODE_PAIR_NORMAL));
}

static inline int ghostcode_color_pair(short pair) {
    return has_colors() ? COLOR_PAIR(pair) : A_REVERSE;
}

static inline void ghostcode_set_normal_theme(void) {
    if (has_colors()) {
        attrset(COLOR_PAIR(GHOSTCODE_PAIR_NORMAL));
        bkgd(COLOR_PAIR(GHOSTCODE_PAIR_NORMAL));
    } else {
        attrset(A_NORMAL);
    }
}

