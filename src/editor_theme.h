static inline void etform_init_theme_pair(
    short pair,
    int foreground_8,
    int background_8,
    int foreground_256,
    int background_256,
    int extended
) {
    if (extended) {
        init_extended_pair(pair, foreground_256, background_256);
    } else {
        init_pair(pair, foreground_8, background_8);
    }
}

