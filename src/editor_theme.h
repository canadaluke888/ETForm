static inline short etform_image_color_pair(uint16_t color) {
    if (!has_colors() || COLORS < 256 ||
        COLOR_PAIRS < ETFORM_IMAGE_PAIR_BASE + ETFORM_IMAGE_COLOR_COUNT ||
        color < ETFORM_IMAGE_COLOR_FIRST ||
        color >= ETFORM_IMAGE_COLOR_FIRST + ETFORM_IMAGE_COLOR_COUNT) {
        return 0;
    }
    return (short)(ETFORM_IMAGE_PAIR_BASE + color - ETFORM_IMAGE_COLOR_FIRST);
}

static inline int etform_color_pair(short pair) {
    return has_colors() ? COLOR_PAIR(pair) : A_REVERSE;
}

static inline void etform_set_normal_theme(void) {
    if (has_colors()) {
        attrset(COLOR_PAIR(ETFORM_PAIR_NORMAL));
        bkgd(COLOR_PAIR(ETFORM_PAIR_NORMAL));
    } else {
        attrset(A_NORMAL);
    }
}

