#define GHOSTCODE_PAIR_FOOTER_SEPARATOR 10
#define GHOSTCODE_PAIR_FOOTER_BORDER 11
#define GHOSTCODE_PAIR_SHADOW 12
#define GHOSTCODE_PAIR_ANNOTATION_BOX_1 13
#define GHOSTCODE_PAIR_ANNOTATION_BOX_2 14
#define GHOSTCODE_PAIR_ANNOTATION_BOX_3 15
#define GHOSTCODE_PAIR_PICKER_DIR 16
#define GHOSTCODE_PAIR_PICKER_FILE 17
#define GHOSTCODE_PAIR_PICKER_ANNOTATED 18
